CREATE TABLE dim_player (
    profile_id      BIGINT PRIMARY KEY,
    name            VARCHAR(255),
    country         VARCHAR(8),
    steam_id        VARCHAR(64),
    last_seen_at    TIMESTAMP,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dim_civilization (
    civ_code        VARCHAR(64) PRIMARY KEY,
    civ_name        VARCHAR(128) NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dim_map (
    map_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_name        VARCHAR(128) NOT NULL UNIQUE,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dim_leaderboard (
    leaderboard_code VARCHAR(32) PRIMARY KEY,
    display_name    VARCHAR(64) NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dim_patch (
    patch_number    INT PRIMARY KEY,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

