CREATE TABLE fact_game_player_score (
    game_id          BIGINT NOT NULL,
    profile_id       BIGINT NOT NULL,
    total_score      INT,
    military_score   INT,
    economy_score    INT,
    technology_score INT,
    society_score    INT,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (game_id, profile_id),
    CONSTRAINT fk_fps_game FOREIGN KEY (game_id) REFERENCES fact_game(game_id),
    CONSTRAINT fk_fps_player FOREIGN KEY (profile_id) REFERENCES dim_player(profile_id)
);

CREATE TABLE fact_game_player_resource (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id          BIGINT NOT NULL,
    profile_id       BIGINT NOT NULL,
    resource_code    VARCHAR(32) NOT NULL,
    second_mark      INT NOT NULL,
    minute_index     INT NOT NULL,
    accumulated_value INT NOT NULL,
    per_minute_value INT,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_fpr_game FOREIGN KEY (game_id) REFERENCES fact_game(game_id),
    CONSTRAINT fk_fpr_player FOREIGN KEY (profile_id) REFERENCES dim_player(profile_id),
    CONSTRAINT fk_fpr_resource FOREIGN KEY (resource_code) REFERENCES dim_resource_type(resource_code),
    CONSTRAINT uq_fpr UNIQUE (game_id, profile_id, resource_code, second_mark)
);

CREATE INDEX idx_fpr_game_player ON fact_game_player_resource(game_id, profile_id);
CREATE INDEX idx_fpr_minute ON fact_game_player_resource(minute_index);

CREATE TABLE fact_game_player_army_value (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id          BIGINT NOT NULL,
    profile_id       BIGINT NOT NULL,
    second_mark      INT NOT NULL,
    minute_index     INT NOT NULL,
    army_value       INT NOT NULL,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_fpav_game FOREIGN KEY (game_id) REFERENCES fact_game(game_id),
    CONSTRAINT fk_fpav_player FOREIGN KEY (profile_id) REFERENCES dim_player(profile_id),
    CONSTRAINT uq_fpav UNIQUE (game_id, profile_id, second_mark)
);

CREATE INDEX idx_fpav_game_player ON fact_game_player_army_value(game_id, profile_id);

CREATE TABLE fact_build_event (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id          BIGINT NOT NULL,
    profile_id       BIGINT NOT NULL,
    event_second     INT NOT NULL,
    entity_type      VARCHAR(32) NOT NULL,
    pbgid            BIGINT,
    event_kind       VARCHAR(16) NOT NULL,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_fbe_game FOREIGN KEY (game_id) REFERENCES fact_game(game_id),
    CONSTRAINT fk_fbe_player FOREIGN KEY (profile_id) REFERENCES dim_player(profile_id)
);

CREATE INDEX idx_fbe_game_player ON fact_build_event(game_id, profile_id);
CREATE INDEX idx_fbe_second ON fact_build_event(event_second);
